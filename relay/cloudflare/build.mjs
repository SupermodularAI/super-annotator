// Build step for the Cloudflare relay:
//  1. src/protocol.generated.js: the sync-protocol block of annotator.js as an
//     ES module, so the Worker applies ops with the exact client reducer.
//  2. dist/: the live-dashboard demo with the current annotator inlined, plus
//     brand fonts when a local superbrand clone is available (never committed).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const skill = path.resolve(here, '..', '..');
const require = createRequire(import.meta.url);
const { injectAnnotator } = require('../server.js');

const src = fs.readFileSync(path.join(skill, 'annotator.js'), 'utf8');
const a = src.indexOf('/* sync-protocol:start */'), b = src.indexOf('/* sync-protocol:end */');
if (a < 0 || b < a) throw new Error('sync-protocol block not found');
fs.writeFileSync(path.join(here, 'src', 'protocol.generated.js'),
  '// GENERATED by build.mjs from annotator.js. Do not edit.\n' + src.slice(a, b) +
  '\nexport { validateEmail, validateIdentity, sanitizeNote, sanitizeReply, applySyncOp };\n');

const dist = path.join(here, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
const html = fs.readFileSync(path.join(skill, 'examples', 'live-dashboard', 'index.html'), 'utf8');
fs.writeFileSync(path.join(dist, 'index.html'), injectAnnotator(html));
fs.writeFileSync(path.join(dist, 'robots.txt'), 'User-agent: *\nDisallow: /\n');

const fonts = process.env.SM_BRAND_FONTS || '';   // optional: a folder with brand fonts, never committed
const wanted = [['Denim INK', 'DenimINK-Regular.woff2'], ['Denim INK', 'DenimINK-SemiBold.woff2'], ['Aeonik Fono', 'aeonikfono-regular.woff2'], ['Aeonik Fono', 'aeonikfono-semibold.woff2']];
let copied = 0;
for (const [fam, file] of wanted) {
  const from = path.join(fonts, fam, file);
  if (!fs.existsSync(from)) continue;
  fs.mkdirSync(path.join(dist, 'fonts', fam), { recursive: true });
  fs.copyFileSync(from, path.join(dist, 'fonts', fam, file));
  copied++;
}
console.log(`built: protocol + dist/index.html, ${copied}/4 brand fonts`);
